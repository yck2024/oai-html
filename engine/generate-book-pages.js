#!/usr/bin/env node
'use strict';

// Generates one static folder per book (<series>/<id>/index.html) so a direct load of
// /<series>/<id>/ returns a real page on GitHub Pages instead of a 404. Each generated page is
// the shelf's own index.html with a <base> tag added (so its relative script/style/image/audio
// references still resolve against the series folder, regardless of the extra path depth) and
// its GA4 page_title/<title> baked in for that one book. This file is deployed unmodified into
// every series folder; it reads that series' own index.html, stories.js, and series.config.js
// via __dirname, exactly as the original taiwan-ehon-only generator did. Re-run after editing
// stories.js or index.html; book-pages.test.js fails if the checked-in folders go stale.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;
const TEMPLATE_PATH = path.join(ROOT, 'index.html');
const CHARSET_META = '<meta charset="utf-8">';

const RUBY = /\{([^|{}]+)\|([^|{}]+)\}/g;
function plainJapanese(text) {
  return text.replace(RUBY, '$1');
}

function bookTitle(story, config) {
  return `${story.title.zh}｜${plainJapanese(story.title.ja)}${config.siteNameSuffix}`;
}

function escapeForSingleQuotedJs(text) {
  return text.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function escapeHtml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function renderBookPage(story, template, config) {
  const shelfPageTitleLiteral = `page_title: '${escapeForSingleQuotedJs(config.shelfPageTitle)}'`;
  if (!template.includes(shelfPageTitleLiteral)) {
    throw new Error("index.html template shape changed: expected the shelf's literal page_title");
  }
  if (!template.includes(CHARSET_META)) {
    throw new Error('index.html template shape changed: expected a <meta charset="utf-8"> tag');
  }
  const title = bookTitle(story, config);
  const withBase = template.replace(CHARSET_META, `${CHARSET_META}\n  <base href="../">`);
  const withTitle = withBase.replace(shelfPageTitleLiteral, `page_title: '${escapeForSingleQuotedJs(title)}'`);
  const withTag = withTitle.replace(/<title>[^<]*<\/title>/, `<title>${escapeHtml(title)}</title>`);
  return `<!doctype html>\n<!-- Auto-generated by generate-book-pages.js from index.html for book "${story.id}". Do not edit directly; edit index.html or stories.js and re-run the generator. -->\n${withTag.replace(/^<!doctype html>\n/, '')}`;
}

function generate({
  write = true,
  stories = require(path.join(ROOT, 'stories.js')),
  config = require(path.join(ROOT, 'series.config.js')),
} = {}) {
  const template = fs.readFileSync(TEMPLATE_PATH, 'utf8');
  const pages = new Map();
  for (const story of stories) {
    const html = renderBookPage(story, template, config);
    pages.set(story.id, html);
    if (write) {
      const dir = path.join(ROOT, story.id);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'index.html'), html);
    }
  }
  return pages;
}

if (require.main === module) {
  const pages = generate({ write: true });
  console.log(`Generated ${pages.size} book pages: ${[...pages.keys()].join(', ')}`);
}

module.exports = { generate, renderBookPage, bookTitle, plainJapanese };
