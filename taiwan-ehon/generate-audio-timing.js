#!/usr/bin/env node
'use strict';

// Precomputes every narration clip's exact duration (via ffprobe) into <series>/audio-timing.js,
// the manifest continuous.js's buildContinuousTimeline() needs to know where each page and line
// falls in the single continuous-listening Blob without re-measuring anything at runtime. Loads
// as a plain global (window.EhonAudioTiming), like stories.js, so app.js has it synchronously —
// no extra fetch before screen-off listening can start. Checked in like the generated book
// pages; re-run after adding or re-recording any clip, or after regenerating the silence clips in
// engine/silence/. multi-series.test.js/timing-manifest.test.js fail CI if a series' checked-in
// manifest goes stale.
//
// This file is deployed unmodified into every series folder (see engine/build.js); it reads that
// series' own stories.js/series.config.js/silence clips via __dirname, exactly like
// generate-book-pages.js.

const fs = require('node:fs');
const path = require('node:path');
const { execFileSync } = require('node:child_process');

const ROOT = __dirname;
const C = require('./continuous.js');

function defaultProbe(filePath) {
  const output = execFileSync('ffprobe', [
    '-v', 'error', '-show_entries', 'format=duration:packet=duration_time', '-of', 'json', filePath,
  ], { encoding: 'utf8' });
  const probe = JSON.parse(output);
  const durationMs = parseFloat(probe.format.duration) * 1000;
  const bytes = new Uint8Array(fs.readFileSync(filePath));
  const withoutId3 = C.stripId3v2(bytes);
  const withoutVbrHeader = C.stripVbrHeaderFrame(withoutId3);
  const removedFrameMs = withoutVbrHeader.byteLength < withoutId3.byteLength
    ? parseFloat(probe.packets[0].duration_time) * 1000
    : 0;
  return Math.round(durationMs - removedFrameMs);
}

// `probe` and `exists` are injectable so tests can exercise the manifest shape — including a
// clip that is missing from disk — without shelling out to a real ffprobe binary or needing
// real audio files on disk.
function generate({
  write = true,
  stories = require(path.join(ROOT, 'stories.js')),
  languages = require(path.join(ROOT, 'series.config.js')).languages,
  probe = defaultProbe,
  exists = fs.existsSync,
} = {}) {
  const silence = {};
  for (const kind of C.SILENCE_KINDS) {
    const filePath = path.join(ROOT, 'silence', `${kind}.mp3`);
    silence[kind] = exists(filePath) ? probe(filePath) : 0;
  }

  const storyTimings = {};
  for (const story of stories) {
    const lineTimings = {};
    for (const page of story.pages) {
      for (const line of page.lines) {
        for (const lang of languages) {
          if (line[lang] === undefined) continue;
          const filePath = path.join(ROOT, 'audio', story.id, lang, `${line.id}.mp3`);
          if (!exists(filePath)) continue;
          lineTimings[line.id] = lineTimings[line.id] || {};
          lineTimings[line.id][lang] = probe(filePath);
        }
      }
    }
    storyTimings[story.id] = lineTimings;
  }

  const manifest = { silence, stories: storyTimings };
  if (write) fs.writeFileSync(path.join(ROOT, 'audio-timing.js'), renderModule(manifest));
  return manifest;
}

function renderModule(manifest) {
  const header = '// Generated by generate-audio-timing.js from this series\' own audio/*.mp3 clips\n'
    + '// (probed with ffprobe) and engine/silence/*.mp3. Do not edit directly: regenerate this file\n'
    + '// instead — see engine/generate-audio-timing.js.\n';
  const body = "(function (root, data) {\n"
    + "  if (typeof module === 'object' && module.exports) module.exports = data;\n"
    + '  else root.EhonAudioTiming = data;\n'
    + "})(typeof self !== 'undefined' ? self : this, "
    + `${JSON.stringify(manifest, null, 2)});\n`;
  return header + body;
}

if (require.main === module) {
  const manifest = generate({ write: true });
  const storyIds = Object.keys(manifest.stories);
  const clipCount = Object.values(manifest.stories)
    .reduce((sum, lines) => sum + Object.values(lines).reduce((count, byLang) => count + Object.keys(byLang).length, 0), 0);
  console.log(`Wrote audio-timing.js: ${clipCount} clip(s) across ${storyIds.length} stor${storyIds.length === 1 ? 'y' : 'ies'}.`);
}

module.exports = { generate, defaultProbe };
