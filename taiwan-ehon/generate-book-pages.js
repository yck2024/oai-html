#!/usr/bin/env node
'use strict';

// Generates one static folder per book (taiwan-ehon/<id>/index.html) so a direct load of
// /taiwan-ehon/<id>/ returns a real page on GitHub Pages instead of a 404. Each generated
// page is the shelf's own index.html with a <base> tag added (so its relative script/style/
// image/audio references still resolve against taiwan-ehon/, regardless of the extra path
// depth) and its GA4 page_title/<title> baked in for that one book. Re-run this after editing
// stories.js or index.html; book-pages.test.js fails if the checked-in folders go stale.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;
const TEMPLATE_PATH = path.join(ROOT, 'index.html');
const SHELF_PAGE_TITLE_LITERAL = "page_title: 'Taiwan story picture books'";
const CHARSET_META = '<meta charset="utf-8">';

const RUBY = /\{([^|{}]+)\|([^|{}]+)\}/g;
function plainJapanese(text) {
  return text.replace(RUBY, '$1');
}

function bookTitle(story) {
  return `${story.title.zh}｜${plainJapanese(story.title.ja)} · 台灣故事繪本`;
}

function escapeForSingleQuotedJs(text) {
  return text.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
}

function escapeHtml(text) {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
}

function renderBookPage(story, template) {
  if (!template.includes(SHELF_PAGE_TITLE_LITERAL)) {
    throw new Error("index.html template shape changed: expected the shelf's literal page_title");
  }
  if (!template.includes(CHARSET_META)) {
    throw new Error('index.html template shape changed: expected a <meta charset="utf-8"> tag');
  }
  const title = bookTitle(story);
  const withBase = template.replace(CHARSET_META, `${CHARSET_META}\n  <base href="../">`);
  const withTitle = withBase.replace(SHELF_PAGE_TITLE_LITERAL, `page_title: '${escapeForSingleQuotedJs(title)}'`);
  const withTag = withTitle.replace(/<title>[^<]*<\/title>/, `<title>${escapeHtml(title)}</title>`);
  return `<!doctype html>\n<!-- Auto-generated by generate-book-pages.js from index.html for book "${story.id}". Do not edit directly; edit index.html or stories.js and re-run the generator. -->\n${withTag.replace(/^<!doctype html>\n/, '')}`;
}

function generate({ write = true, stories = require(path.join(ROOT, 'stories.js')) } = {}) {
  const template = fs.readFileSync(TEMPLATE_PATH, 'utf8');
  const pages = new Map();
  for (const story of stories) {
    const html = renderBookPage(story, template);
    pages.set(story.id, html);
    if (write) {
      const dir = path.join(ROOT, story.id);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'index.html'), html);
    }
  }
  return pages;
}

if (require.main === module) {
  const pages = generate({ write: true });
  console.log(`Generated ${pages.size} book pages: ${[...pages.keys()].join(', ')}`);
}

module.exports = { generate, renderBookPage, bookTitle, plainJapanese };
