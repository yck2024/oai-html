'use strict';

// Regenerates precache-manifest.js from each game's images/ and audio/ folders on disk, so the
// service worker's offline media list can never drift from what actually ships in the app.
// Run with: node math-island/generate-precache-manifest.js

const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;

// Every game Math Island covers. Poko has no static images (its scene is emoji/CSS/three.js);
// Number Garden and Rag and the Echo Forest each have their own images and/or audio folders.
const GAMES = ['poko', 'number-garden', 'dino-spirit'];

function listFiles(dir, extension) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  const entries = fs.readdirSync(abs, { withFileTypes: true, recursive: true });
  const files = [];
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(extension)) continue;
    const relDir = path.relative(abs, entry.parentPath ?? entry.path);
    const relPath = relDir ? `${relDir}/${entry.name}` : entry.name;
    files.push(`${dir}/${relPath.split(path.sep).join('/')}`);
  }
  return files.sort();
}

function buildManifest() {
  const images = [];
  const audio = [];
  for (const game of GAMES) {
    images.push(...listFiles(`${game}/images`, '.webp'));
    audio.push(...listFiles(`${game}/audio`, '.mp3'));
  }
  return { IMAGES: images.sort(), AUDIO: audio.sort() };
}

function render(manifest) {
  const body = JSON.stringify(manifest, null, 2);
  return `'use strict';

// Generated by generate-precache-manifest.js — do not hand-edit. Regenerate after adding,
// removing, or renaming any file under poko/, number-garden/, or dino-spirit/'s images/ or audio/.
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.MathIslandPrecacheManifest = api;
})(typeof self !== 'undefined' ? self : this, () => (${body}));
`;
}

function main() {
  const manifest = buildManifest();
  fs.writeFileSync(path.join(ROOT, 'precache-manifest.js'), render(manifest));
  console.log(`Wrote precache-manifest.js: ${manifest.IMAGES.length} images, ${manifest.AUDIO.length} audio clips.`);
}

if (require.main === module) main();

module.exports = { buildManifest, GAMES };
