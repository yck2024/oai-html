'use strict';

// Regenerates precache-manifest.js from the images/ and audio/ folders on disk, so the
// service worker's offline media list can never drift from what actually ships in the app.
// Run with: node monster-word-arena-tw/generate-precache-manifest.js

const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = __dirname;

function listFiles(dir, extension) {
  const abs = path.join(ROOT, dir);
  const entries = fs.readdirSync(abs, { withFileTypes: true, recursive: true });
  const files = [];
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(extension)) continue;
    const relDir = path.relative(abs, entry.parentPath ?? entry.path);
    const relPath = relDir ? `${relDir}/${entry.name}` : entry.name;
    files.push(`${dir}/${relPath.split(path.sep).join('/')}`);
  }
  return files.sort();
}

function buildManifest() {
  const images = listFiles('images', '.webp');
  const audio = listFiles('audio', '.mp3');
  const mediaVersion = crypto.createHash('sha256');
  for (const file of [...images, ...audio]) {
    mediaVersion.update(file);
    mediaVersion.update(fs.readFileSync(path.join(ROOT, file)));
  }
  return { IMAGES: images, AUDIO: audio, MEDIA_VERSION: mediaVersion.digest('hex').slice(0, 12) };
}

function render(manifest) {
  const body = JSON.stringify(manifest, null, 2);
  return `'use strict';

// Generated by generate-precache-manifest.js — do not hand-edit. Regenerate after adding,
// removing, or renaming any file under images/ or audio/.
(function (root, factory) {
  const api = factory();
  if (typeof module === 'object' && module.exports) module.exports = api;
  else root.MonsterWordArenaPrecacheManifest = api;
})(typeof self !== 'undefined' ? self : this, () => (${body}));
`;
}

function main() {
  const manifest = buildManifest();
  fs.writeFileSync(path.join(ROOT, 'precache-manifest.js'), render(manifest));
  console.log(`Wrote precache-manifest.js: ${manifest.IMAGES.length} images, ${manifest.AUDIO.length} audio clips.`);
}

if (require.main === module) main();

module.exports = { buildManifest };
